def list_genres() -> list:
    return list(GENRES.keys())


def get_genre_rules(genre: str) -> str:
    g = GENRES.get(genre)
    if not g:
        return ""
    lines = [f"【题材：{genre}】", f"节奏：{g['pacing']}"]
    lines.append("特有爽点：" + " / ".join(g["cool_points"]))
    lines.append("题材规则：")
    for r in g["special_rules"]:
        lines.append(f"  - {r}")
    return "\n".join(lines)
